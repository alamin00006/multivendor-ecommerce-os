export type SellerKey = 'gadget' | 'deshi' | 'fresh';

export interface ProductTemplate {
  title: string;
  titleBn: string;
  brand: string;
  /** Base price in taka. */
  price: number;
  /** Percent above price used for compareAtPrice (0 = no strike-through price). */
  markup: number;
  /** Variant dimensions, e.g. { color: ['Black', 'Blue'] }. Empty object = single variant. */
  options: Record<string, string[]>;
  /** Extra taka added per option value index of the first dimension (e.g. storage tiers). */
  tierStep?: number;
  description: string;
}

export interface SubCategoryData {
  name: string;
  nameBn: string;
  slug: string;
  products: [ProductTemplate, ProductTemplate];
}

export interface CategoryData {
  name: string;
  nameBn: string;
  slug: string;
  seller: SellerKey;
  children: [SubCategoryData, SubCategoryData, SubCategoryData];
}


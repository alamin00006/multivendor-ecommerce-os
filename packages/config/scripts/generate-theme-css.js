import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import tokens from '../tokens/tokens.js';

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'tokens');
const lines = ['/* Generated by scripts/generate-theme-css.js — do not edit by hand. */', '@theme {'];

for (const [name, value] of Object.entries(tokens.colors)) {
  if (typeof value === 'string') lines.push(`  --color-${name}: ${value};`);
  else for (const [shade, hex] of Object.entries(value)) lines.push(`  --color-${name}-${shade}: ${hex};`);
}
for (const [name, value] of Object.entries(tokens.radius)) lines.push(`  --radius-${name}: ${value};`);
for (const [name, value] of Object.entries(tokens.fontFamily)) lines.push(`  --font-${name}: ${value.join(', ')};`);
for (const [name, value] of Object.entries(tokens.shadow)) lines.push(`  --shadow-${name}: ${value};`);
lines.push(`  --container-site: ${tokens.layout.container};`);
lines.push(`  --container-header: ${tokens.layout.header};`);
lines.push('}', '');

writeFileSync(join(outDir, 'theme.css'), lines.join('\n'));
writeFileSync(join(outDir, 'tokens.json'), JSON.stringify(tokens, null, 2) + '\n');
console.log('theme.css + tokens.json generated');
